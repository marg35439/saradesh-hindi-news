const LOCAL_STORAGE_KEY = "dainik_bhaskar_news_v2";

export function getLocalArticles(): Article[] {
  try {
    const data = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (data) {
      const parsed = JSON.parse(data);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.warn("Failed to read local articles:", err);
  }
  return FALLBACK_NEWS;
}

export function saveLocalArticles(articles: Article[]): void {
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(articles));
  } catch (err) {
    console.warn("Failed to save local articles:", err);
  }
}

