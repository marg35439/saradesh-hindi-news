// Helper to get local articles or default
export function getLocalArticles(): Article[] {
  try {
    const saved = localStorage.getItem("sara_local_news");
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error("Error reading local news cache", e);
  }
  return FALLBACK_NEWS;
}

// Helper to save local articles
export function saveLocalArticles(articles: Article[]): void {
  try {
    localStorage.setItem("sara_local_news", JSON.stringify(articles));
  } catch (e) {
    console.error("Error saving local news cache", e);
  }
}
