// GET /api/weather
app.get("/api/weather", async (req, res) => {
  const bases = {
    "दिल्ली": { temp: 40, text: "तेज धूप", icon: "Sun" },
    "मुंबई": { temp: 32, text: "उमस और बादल", icon: "CloudSun" },
    "रांची": { temp: 34, text: "मौसम सुहावना", icon: "Cloud" },
    "भोपाल": { temp: 36, text: "हल्के बादल", icon: "CloudSun" },
    "जयपुर": { temp: 41, text: "भीषण गर्मी", icon: "Sun" }
  };

  const hourOfDay = (new Date().getUTCHours() + 5.5) % 24; // Indian Standard Time offset

  const weatherData: Record<string, { temp: number; text: string; icon: string }> = {};

  for (const [city, info] of Object.entries(bases)) {
    // Dynamic change based on hour of the day (cooler at night/morning, peak heat around 2pm-3pm)
    const diffFromPeak = Math.abs(hourOfDay - 14); // peak at 14:00 (2 PM)
    const factor = Math.max(0, 8 - diffFromPeak) * 0.8; // Max 6.4 degrees drop at night/early morning
    const cycleDrop = 6.4 - factor; 

    // Add small random fluctuation (-0.8 to +0.8)
    const fluctuation = (Math.random() * 1.6) - 0.8;
    const finalTemp = Math.round(info.temp - cycleDrop + fluctuation);

    // Dynamic weather text & icon based on temp
    let text = info.text;
    let icon = info.icon;

    if (city === "दिल्ली") {
      if (finalTemp >= 41) { text = "भीषण गर्मी (लू)"; icon = "Sun"; }
      else if (finalTemp >= 37) { text = "तेज धूप"; icon = "Sun"; }
      else { text = "हल्की गर्मी"; icon = "CloudSun"; }
    } else if (city === "जयपुर") {
      if (finalTemp >= 42) { text = "तपती गर्मी (रेत गरम)"; icon = "Sun"; }
      else { text = "तेज धूप"; icon = "Sun"; }
    } else if (city === "मुंबई") {
      const isRainy = Math.random() > 0.4;
      text = isRainy ? "हल्की रिमझिम बारिश" : "उमस भरा मौसम";
      icon = isRainy ? "CloudRain" : "Cloud";
    } else if (city === "रांची") {
      if (finalTemp > 34) { text = "सामान्य धूप"; icon = "CloudSun"; }
      else { text = "मौसम सुहावना"; icon = "Cloud"; }
    } else if (city === "भोपाल") {
      if (finalTemp >= 38) { text = "गर्मी"; icon = "Sun"; }
      else { text = "आंशिक रूप से बादल"; icon = "CloudSun"; }
    }

    weatherData[city] = {
      temp: finalTemp,
      text: text,
      icon: icon
    };
  }

  res.json(weatherData);
});

// GET all news from Firestore (Seeds DEFAULT_NEWS if database is empty)

app.get("/api/news", async (req, res) => {
  try {
    const querySnapshot = await getDocs(collection(db, "articles"));
    let articles: any[] = [];
    querySnapshot.forEach((doc) => {
      articles.push({ id: doc.id, ...doc.data() });
    });

    // Sort by createdAt descending
    articles.sort((a, b) => {
      const dateA = a.createdAt ? new Date(a.createdAt).getTime() : 0;
      const dateB = b.createdAt ? new Date(b.createdAt).getTime() : 0;
      return dateB - dateA;
    });

    // Seed if empty or enrich items if existing items have incomplete text
    if (articles.length === 0) {
      console.log("Firestore articles collection is empty. Seeding DEFAULT_NEWS...");
      for (const item of DEFAULT_NEWS) {
        const docRef = doc(db, "articles", item.id);
        const seededItem = {
          ...item,
          createdAt: item.createdAt || new Date().toISOString()
        };
        await setDoc(docRef, seededItem);
        articles.push(seededItem);
      }
      articles.sort((a, b) => {
        const dateA = a.createdAt ? new Date(a.createdAt).getTime() : 0;
        const dateB = b.createdAt ? new Date(b.createdAt).getTime() : 0;
        return dateB - dateA;
      });
    } else {
      // Ensure all default articles have strictly correct categories and updated content
      for (const defItem of DEFAULT_NEWS) {
        const existingDoc = articles.find(a => a.id === defItem.id);
        if (!existingDoc) {
          // If a new default article was added to DEFAULT_NEWS, add it to Firestore
          const docRef = doc(db, "articles", defItem.id);
          const newItem = { ...defItem, createdAt: new Date().toISOString() };
          await setDoc(docRef, newItem).catch(() => {});
          articles.push(newItem);
        } else {
          // Always ensure category and core fields match the canonical DEFAULT_NEWS specification
          if (existingDoc.category !== defItem.category || !existingDoc.content || existingDoc.content.length < 300) {
            const docRef = doc(db, "articles", defItem.id);
            const updatedData = {
              ...existingDoc,
              title: defItem.title,
              subtitle: defItem.subtitle,
              content: defItem.content,
              category: defItem.category,
              state: defItem.state || existingDoc.state || "",
              image: defItem.image,
              author: defItem.author,
              tags: defItem.tags,
              readTime: defItem.readTime
            };
            await setDoc(docRef, updatedData, { merge: true }).catch(() => {});
            Object.assign(existingDoc, updatedData);
          }
        }
      }
    }

    // Filter by category if query exists
    const category = req.query.category;
    if (category && category !== "all") {
      articles = articles.filter((a: any) => a.category === category);
    }

    // Filter by state if category is state and state query exists
    const state = req.query.state;
    if (category === "state" && state && state !== "सभी राज्य") {
      articles = articles.filter((a: any) => 
        a.state === state || 
        (a.title && a.title.includes(state)) || 
        (a.content && a.content.includes(state))
      );
    }

    // Filter by search query if search parameter exists
    const search = req.query.search;
    if (search && typeof search === 'string' && search.trim()) {
      const q = search.trim().toLowerCase();
      articles = articles.filter((a: any) =>
        (a.title && a.title.toLowerCase().includes(q)) ||
        (a.subtitle && a.subtitle.toLowerCase().includes(q)) ||
        (a.content && a.content.toLowerCase().includes(q)) ||
        (a.tags && Array.isArray(a.tags) && a.tags.some((t: string) => t.toLowerCase().includes(q)))
      );
    }

    res.json(articles);
  } catch (err: any) {
    console.error("Error fetching news list: ", err);
    res.status(500).json({ error: err.message });
  }
});

// GET news by ID
app.get("/api/news/:id", async (req, res) => {
  const articleId = req.params.id;
  const docRef = doc(db, "articles", articleId);
  try {
    const docSnap = await getDoc(docRef);
    if (!docSnap.exists()) {
      // Fallback check in DEFAULT_NEWS
      const defItem = DEFAULT_NEWS.find(d => d.id === articleId);
      if (defItem) {
        return res.json(defItem);
      }
      return res.status(404).json({ error: "आलेख नहीं मिला!" });
    }
    const data = docSnap.data();
    const defMatch = DEFAULT_NEWS.find(d => d.id === articleId);
    if (defMatch && (!data.content || data.content.length < 350 || !data.content.includes("##"))) {
      const enriched = {
        id: docSnap.id,
        ...data,
        title: defMatch.title,
        subtitle: defMatch.subtitle,
        content: defMatch.content,
        author: defMatch.author,
        tags: defMatch.tags
      };
      return res.json(enriched);
    }
    return res.json({ id: docSnap.id, ...data });
  } catch (err: any) {
    console.error("Error fetching article by ID:", err);
    return res.status(500).json({ error: err.message });
  }
});

